package ru.stalkerzone.sim;

/**
 * Товары, которые ходят по Зоне. base — базовая цена в рублях.
 *
 * <p>Оружие, патроны и броня бывают трёх происхождений (v1.12):
 * <ul>
 *   <li>кустарные ({@link #AMMO}, {@link #GEAR}) — делают только группировки в своих мастерских; торговцы их скупают
 *       и перепродают, на Большой земле на них спроса нет;</li>
 *   <li>прототипы ({@link #PROTO}) — универсальные комплекты, которые собирают в Зоне техники учёных:
 *       чуть слабее лучшего фракционного, зато сбалансированы; их закупают торговцы на перепродажу;</li>
 *   <li>с Большой земли ({@link #AMMO_PRO}, {@link #GEAR_PRO}) — заводские: лучше в перестрелке, броня хуже держит аномалии;
 *       стоят дороже, группировки берут их только под особые задачи для своих профессиональных групп.</li>
 * </ul>
 * Новые товары добавляются в конец: порядок значений входит в формат сохранения.
 */
public enum Good {
    FOOD("Еда", 20, true),
    PARTS("Детали", 25, true),
    AMMO("Патроны кустарные", 15, false),
    MEDS("Медикаменты", 60, true),
    GEAR("Снаряжение кустарное", 350, false),
    ARTIFACT("Артефакты", 900, true),
    /** Цемент, доски, профлист, арматура: только на стройку и ремонт. Возят с Большой земли через торговцев. */
    MATERIALS("Стройматериалы", 30, true),
    PROTO("Прототипы снаряжения", 560, false),
    AMMO_PRO("Патроны заводские", 38, true),
    GEAR_PRO("Снаряжение с Большой земли", 800, true);

    public static final Good[] ALL = values();
    /** Сколько товаров было в сохранении, которое сейчас читается (старые сохранения короче). */
    static int readCount = ALL.length;

    public final String ru;
    public final int base;
    /** Есть ли у товара рынок на Большой земле (кустарное и прототипы туда не продаются и оттуда не завозятся). */
    public final boolean mainland;

    Good(String ru, int base, boolean mainland) {
        this.ru = ru;
        this.base = base;
        this.mainland = mainland;
    }

    /** Патроны любого происхождения. */
    public boolean isAmmo() { return this == AMMO || this == AMMO_PRO; }

    /** Снаряжение (оружие и броня) любого происхождения. */
    public boolean isGear() { return this == GEAR || this == PROTO || this == GEAR_PRO; }
}
