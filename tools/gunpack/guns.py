def hands(g, z=-2.0):
    g.marker('lefthand_pos', [-7, 8, z], [3, 12, 4])
    g.marker('righthand_pos', [4, 8, z], [3, 12, 4])


def seg_chain(g, bone, start, angles, length, half_w, depth0, depth1, m, rib=None):
    """Изогнутая деталь (магазин): цепочка брусков, каждый наклонён вперёд сильнее предыдущего.
    start = (y, z) верхней середины, angles в градусах от вертикали вперёд (к дулу)."""
    y, z = start
    n = len(angles)
    for i, a in enumerate(angles):
        t = math.radians(a)
        dy, dz = -math.cos(t) * length, -math.sin(t) * length
        cy, cz = y + dy / 2, z + dz / 2
        d = depth0 + (depth1 - depth0) * i / max(1, n - 1)
        g.box(bone, -half_w, cy - length / 2 - 0.06, cz - d / 2, half_w, cy + length / 2 + 0.06, cz + d / 2, m,
              rot=[-a, 0, 0], piv=[0, cy, cz])
        if rib:
            g.box(bone, -half_w - 0.05, cy - length / 2 + 0.25, cz - d / 2 + 0.25, half_w + 0.05, cy + length / 2 - 0.25, cz - d / 2 + 0.55,
                  rib, rot=[-a, 0, 0], piv=[0, cy, cz])
        y, z = y + dy, z + dz
    return y, z


